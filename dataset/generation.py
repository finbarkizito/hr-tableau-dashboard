"""
HumanResources.csv — Synthetic Workforce Dataset Generator
==========================================================

Purpose
-------
This script generates a realistic-but-synthetic HR dataset for analytics and BI dashboards.
It is designed to support common workforce questions such as:
- Headcount distribution by location and department
- Salary equity checks (e.g., gender x education)
- Tenure / age segmentation
- Attrition (termination) patterns over time
- Performance and overtime patterns by role

Key Design Choices (Why this isn't "random noise")
--------------------------------------------------
1) Controlled distributions:
   - States are assigned with weighted probabilities (HQ-heavy).
   - Departments and job titles are assigned with weighted probabilities to mimic org structure.

2) Business rules:
   - Education level depends on job title (e.g., Manager roles skew higher education).
   - Termination date must occur at least 6 months after hire date.
   - Salary is generated by department + job title bands, then adjusted by education + gender
     multipliers and an age-based increment to create measurable patterns.


Outputs
-------
- A CSV file: HumanResources.csv
- Columns include employee demographics, role info, dates, salary, performance, overtime, and termdate.

Notes / Caveats
---------------
- This is synthetic data: insights are useful for demonstrating analysis + dashboard design,
  but not to represent real-world outcomes.
"""

