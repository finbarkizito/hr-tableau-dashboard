def generate_custom_hiredate(year_weights: dict) -> datetime:
    """Generate a hire date using weighted year selection and a random day/month."""
    year = random.choices(list(year_weights.keys()), weights=list(year_weights.values()))[0]
    # Use Faker to generate a datetime within that year.
    return fake.date_time_between(
        start_date=datetime(year, 1, 1),
        end_date=datetime(year, 12, 31)
    )

