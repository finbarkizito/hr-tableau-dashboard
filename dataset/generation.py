# -----------------------------------------------------------------------
# 8) Salary adjustment model: encode "detectable patterns" for analytics
# -----------------------------------------------------------------------
# These multipliers intentionally create a measurable pay-gap pattern by education x gender,
# which is useful for demonstrating equity analysis in Tableau.
education_multiplier = {
    'High School': {'Male': 1.03, 'Female': 1.00},
    "Bachelor":   {'Male': 1.115, 'Female': 1.00},
    "Master":     {'Male': 1.00,  'Female': 1.07},
    'PhD':        {'Male': 1.00,  'Female': 1.17}
}

def calculate_age(birthdate: pd.Timestamp) -> int:
    """Calculate age based on today's date."""
    today = pd.Timestamp('today')
    return today.year - birthdate.year - ((today.month, today.day) < (birthdate.month, birthdate.day))

def calculate_adjusted_salary(row: pd.Series) -> int:
    """
    Adjust salary so it depends on:
    - Base salary (role/department)
    - Education x Gender multiplier (pay equity pattern)
    - Age-based increment (proxy for experience / seniority)

    The goal: salaries aren't random; they're explainable and analyzable.
    """
    base_salary = row['salary']
    gender = row['gender']
    education = row['education_level']

    # Education x gender multiplier
    multiplier = education_multiplier.get(education, {}).get(gender, 1.0)
    adjusted_salary = base_salary * multiplier

    # Age increment (0.1% to 0.3% per year) to add a realistic upward drift with age
    age = calculate_age(pd.to_datetime(row['birthdate']))
    age_increment = 1 + np.random.uniform(0.001, 0.003) * age
    adjusted_salary *= age_increment

    # Never reduce below base salary
    adjusted_salary = max(adjusted_salary, base_salary)

    return int(round(adjusted_salary))

