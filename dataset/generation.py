# 10) Add birthdate (age distribution + role constraints)
# -------------------------------------------------------
def generate_birthdate(row: pd.Series):
    """
    Generate birthdate using an age distribution, with realistic overrides:
    - Managers skew older
    - PhD skew older than average
    """
    age_distribution = {
        'under_25': 0.11,
        '25_34': 0.25,
        '35_44': 0.31,
        '45_54': 0.24,
        'over_55': 0.09
    }

    age_groups = list(age_distribution.keys())
    age_probs  = list(age_distribution.values())

    chosen_group = np.random.choice(age_groups, p=age_probs)

    if 'Manager' in row['job_title']:
        age = np.random.randint(30, 65)
    elif row['education_level'] == 'PhD':
        age = np.random.randint(27, 65)
    elif chosen_group == 'under_25':
        age = np.random.randint(20, 25)
    elif chosen_group == '25_34':
        age = np.random.randint(25, 35)
    elif chosen_group == '35_44':
        age = np.random.randint(35, 45)
    elif chosen_group == '45_54':
        age = np.random.randint(45, 55)
    else:
        age = np.random.randint(56, 65)

    return fake.date_of_birth(minimum_age=age, maximum_age=age)

